/** Locale build settings for scripts/i18n-build.mjs (adapted from the south-africa site). */
import fs from 'node:fs';
import path from 'node:path';

const META = {
  fr: { intl: 'fr-FR', og: 'fr_FR' },
  de: { intl: 'de-DE', og: 'de_DE' },
  es: { intl: 'es-ES', og: 'es_ES' },
};

const config = {
  locales: ['fr', 'de', 'es'],
  enAppDir: 'app/(en)',
  sharedDirs: ['components', 'lib', 'data', 'config', 'content'],
  after(locale, root) {
    const out = path.join(root, '.i18n', locale);
    // lib/locale.ts: the locale constants for this copy (written from the English source, untranslated).
    const src = fs.readFileSync(path.join(root, 'lib', 'locale.ts'), 'utf8')
      .replace('export const locale: Locale = "en";', `export const locale: Locale = "${locale}";`)
      .replace('export const intlLocale = "en-GB";', `export const intlLocale = "${META[locale].intl}";`)
      .replace('export const ogLocale = "en_GB";', `export const ogLocale = "${META[locale].og}";`)
      .replace('export const localePrefix = "";', `export const localePrefix = "/${locale}";`)
      .replace('export const homePath = "/";', `export const homePath = "/${locale}";`);
    if (!src.includes(`homePath = "/${locale}"`)) throw new Error('lib/locale.ts: constants not found');
    fs.writeFileSync(path.join(out, 'lib', 'locale.ts'), `// GENERATED by scripts/i18n-build.mjs from lib/locale.ts. Do not edit.\n${src}`);
    // data/media.json: translate alt text (the manifest is JSON, so the code translator does not see it).
    const dict = JSON.parse(fs.readFileSync(path.join(root, 'i18n', `${locale}.json`), 'utf8'));
    const media = JSON.parse(fs.readFileSync(path.join(root, 'data', 'media.json'), 'utf8'));
    for (const group of Object.values(media)) {
      for (const item of Object.values(group)) {
        if (item && typeof item.alt === 'string' && dict[item.alt]) item.alt = dict[item.alt];
      }
    }
    fs.writeFileSync(path.join(out, 'data', 'media.json'), JSON.stringify(media, null, 1) + '\n');
  },
  /** Extra strings for translators that live outside code (JSON manifest alt text). */
  extraStrings(root) {
    const media = JSON.parse(fs.readFileSync(path.join(root, 'data', 'media.json'), 'utf8'));
    return Object.values(media).flatMap((g) => Object.values(g).map((x) => x.alt)).filter(Boolean);
  },
};

export default config;
